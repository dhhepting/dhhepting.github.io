#!/usr/bin/env node
// gen-readme.mjs -- regenerate the .mjs index inside a README.md.
//
//   node gen-readme.mjs <dir>           rewrite <dir>/README.md (creates it if absent)
//   node gen-readme.mjs <dir> --check   exit 1 if README.md is out of date (for CI / hooks)
//   node gen-readme.mjs <dir> --stdout  print the generated block only
//   add --all to list every .mjs, ignoring the Jekyll configuration
//   --apps-base=<dir>   where the modular apps live (default experimental/modular)
//   --downloads=<dir>   where the build puts source downloads (default dist/downloads)
//
// Only the text between the BEGIN/END markers is replaced; everything else in
// the README is left alone. Descriptions come from each file's leading // comment.
//
// Files that Jekyll will not publish are left out, so the README never links to them.
// "Not published" is decided the way Jekyll 4 decides it, from the nearest _config.yml
// at or above <dir> (needs the `yaml` package: npm i -D yaml):
//   - paths matching `exclude` are skipped (glob, or path prefix, as Jekyll does it),
//     unless they also match `include`
//   - names starting with . _ # ~ and names ending in ~ are skipped, unless `include`d
// Only _config.yml is read; settings that only an overlay config sets are not seen.
//
// Exception: an unpublished app (a folder under --apps-base containing app.html) is not dropped.
// Its .mjs files are listed with links to the read-only .txt copies that source-zips.mjs writes to
// <downloads>/<App>/, and the app's section links to <downloads>/<App>/index.html and <App>.zip.
// Paths are relative to <dir>, so <dir> should be the Vite root and the README sit beside dist/.

import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, resolve, relative, dirname, basename, sep } from 'node:path';
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';

const args = process.argv.slice(2);
const dirArg = args.find((a) => !a.startsWith('--'));
const flags = new Set(args.filter((a) => a.startsWith('--')));
if (!dirArg) { console.error('usage: gen-readme.mjs <dir> [--check|--stdout] [--all] [--apps-base=<dir>] [--downloads=<dir>]'); process.exit(2); }
const opt = (name, dflt) => {
  const a = args.find((x) => x.startsWith(`--${name}=`));
  return a ? a.slice(name.length + 3).replace(/^\.\//, '').replace(/\/+$/, '') : dflt;
};

const root = dirArg;
const SKIP = new Set(['node_modules', 'dist', '.git']);
const BEGIN = '<!-- BEGIN:mjs-index (generated by gen-readme.mjs; do not edit by hand) -->';
const END = '<!-- END:mjs-index -->';

// ---- Which entries does Jekyll publish? ------------------------------------------------
// Mirrors Jekyll 4.4.1 EntryFilter (lib/jekyll/entry_filter.rb): glob_include?, included?,
// excluded?, special? and backup?. Matching uses absolute paths; Ruby's File.fnmatch? without
// flags, where `*` and `**` both match across '/'.

const toPosix = (p) => p.split(sep).join('/');
const escapeRe = (c) => c.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const DEFAULT_EXCLUDE = ['.sass-cache', '.jekyll-cache', 'gemfiles', 'Gemfile', 'Gemfile.lock',
                         'node_modules', 'vendor/bundle/', 'vendor/cache/', 'vendor/gems/', 'vendor/ruby/'];
const SPECIAL_LEADING = /^[._#~]/;

function globToRegExp(glob) {
  let re = '';
  for (let i = 0; i < glob.length; i++) {
    const c = glob[i];
    if (c === '*') { while (glob[i + 1] === '*') i++; re += '.*'; }
    else if (c === '?') re += '.';
    else if (c === '[' && glob.indexOf(']', i + 2) !== -1) {
      const end = glob.indexOf(']', i + 2);
      const set = glob.slice(i + 1, end);
      re += `[${set[0] === '!' ? '^' + set.slice(1) : set}]`;
      i = end;
    } else if (c === '\\' && i + 1 < glob.length) re += escapeRe(glob[++i]);
    else re += escapeRe(c);
  }
  return new RegExp(`^${re}$`, 's');
}

function findJekyllConfig(start) {
  for (let dir = resolve(start); ; dir = dirname(dir)) {
    if (existsSync(join(dir, '_config.yml'))) return dir;
    if (dirname(dir) === dir) return null;
  }
}

async function loadFilter(startDir) {
  const none = { served: () => true, source: null };
  if (flags.has('--all')) return none;
  const source = findJekyllConfig(startDir);
  if (!source) return none;

  let parse;
  // look for `yaml` next to this script, then from the target dir and cwd upward
  // (the script may live in a shared scripts/ folder while yaml is installed in the project)
  const tryYaml = async () => {
    try { return (await import('yaml')).parse; } catch { /* fall through */ }
    for (const base of [resolve(startDir), process.cwd()]) {
      try { return (await import(pathToFileURL(createRequire(join(base, 'noop.js')).resolve('yaml')).href)).parse; }
      catch { /* try next */ }
    }
    return null;
  };
  parse = await tryYaml();
  if (!parse) {
    console.error(`gen-readme: found ${join(source, '_config.yml')}, but reading it needs the 'yaml' package.\n` +
                  `  npm i -D yaml        (or pass --all to list every .mjs regardless of Jekyll's exclude list)`);
    process.exit(2);
  }
  const cfg = parse(readFileSync(join(source, '_config.yml'), 'utf8'), { uniqueKeys: false }) ?? {};
  const include = cfg.include ?? ['.htaccess'];
  const exclude = [...DEFAULT_EXCLUDE, ...(cfg.exclude ?? [])].filter((p) => !include.includes(p));

  const src = toPosix(resolve(source));
  const compile = (patterns) => patterns.map((p) => {
    const pat = `${src}/${p}`.replace(/\/{2,}/g, '/');
    return { pat, re: globToRegExp(pat) };
  });
  const inc = compile(include), exc = compile(exclude);
  const globInclude = (list, rel, isDir) => {
    const entry = `${src}/${rel}`;
    return list.some(({ pat, re }) => re.test(entry) || entry.startsWith(pat) || (isDir && pat === `${entry}/`));
  };

  // is this one entry (path relative to the Jekyll source dir) published?
  const entryServed = (rel, isDir) => {
    const name = basename(rel);
    // Jekyll's included? checks only the entry's own name (joined onto the source dir)
    const included = globInclude(inc, name, isDir && !rel.includes('/'));
    if (globInclude(exc, rel, isDir) && !included) return false;
    if (included) return true;
    return !(SPECIAL_LEADING.test(name) || name.endsWith('~'));
  };

  // a file is published only if it and every directory above it, up to the Jekyll source dir, are
  const served = (absPath, isDir) => {
    const parts = toPosix(relative(source, resolve(absPath))).split('/');
    if (parts[0] === '..') return true;                    // outside the Jekyll site: not our business
    return parts.every((_, i) => entryServed(parts.slice(0, i + 1).join('/'), i < parts.length - 1 || isDir));
  };
  return { served, source };
}

const { served, source: jekyllSource } = await loadFilter(root);
const skipped = new Map();                                 // excluded path -> number of .mjs files it hides

const appsBase = resolve(root, opt('apps-base', 'experimental/modular'));
const downloads = opt('downloads', 'dist/downloads');
const apps = new Map();                                    // app name -> { dir, count }

// nearest folder at or above `dir`, below appsBase, that holds app.html
function appRootOf(dir) {
  for (let d = resolve(dir); d !== appsBase && d.startsWith(appsBase + sep); d = dirname(d)) {
    if (existsSync(join(d, 'app.html'))) return d;
  }
  return null;
}

// an unpublished entry: link app sources to their .txt downloads, count everything else as skipped
function handleUnserved(p, isDir, entries) {
  const files = isDir ? collectMjs(p) : [p];
  let hidden = 0;
  for (const f of files) {
    const app = appRootOf(dirname(f));
    if (!app) { hidden++; continue; }
    const name = toPosix(relative(appsBase, app)).split('/').join('-');
    const rel = toPosix(relative(root, f));
    entries.push({ path: f, href: `./${downloads}/${name}/${rel}.txt`, app: name });
    const a = apps.get(name) || { count: 0 };
    a.count++; apps.set(name, a);
  }
  if (hidden) skipped.set(toPosix(relative(root, p)) + (isDir ? '/' : ''), hidden);
}

function collectMjs(dir) {
  const out = [];
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    if (SKIP.has(e.name)) continue;
    const p = join(dir, e.name);
    if (e.isDirectory()) out.push(...collectMjs(p));
    else if (e.name.endsWith('.mjs')) out.push(p);
  }
  return out;
}

function walk(dir) {
  const out = [];
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    if (SKIP.has(e.name)) continue;
    const p = join(dir, e.name);
    if (e.isDirectory()) {
      if (served(p, true)) out.push(...walk(p));
      else handleUnserved(p, true, out);
    } else if (e.name.endsWith('.mjs')) {
      if (served(p, false)) out.push(p);
      else handleUnserved(p, false, out);
    }
  }
  return out;
}

// First sentence of the leading // comment block, or '' if the file has none.
function describe(path) {
  const lines = readFileSync(path, 'utf8').split('\n');
  const body = [];
  for (const l of lines) {
    const m = l.match(/^\s*\/\/(.*)$/);
    if (!m) { if (body.length || l.trim() !== '') break; else continue; }
    const t = m[1].replace(/^[\s\/]+|[\s\/]+$/g, '');   // drop banner slashes
    if (t) body.push(t);
  }
  // Drop a leading "name", "name.js" or "name.c - " title line.
  while (body.length && /^[\w.-]+$/.test(body[0])) body.shift();
  if (!body.length) return '';
  let text = body.slice(0, 3).join(' ')
    .replace(/^[\w.-]+\s+(--|-)\s+/, '');                // "main.mjs -- the controller" -> "the controller"
  const sentence = text.match(/^.*?[.!?](\s|$)/);        // first sentence
  text = (sentence ? sentence[0] : text).trim();
  if (text.length > 160) text = text.slice(0, 157).trimEnd() + '...';
  return text.replace(/\|/g, '\\|');
}

const files = walk(root)
  .map((f) => (typeof f === 'string' ? { path: f, href: `./${toPosix(relative(root, f))}` } : f))
  .sort((a, b) => dirname(a.path).localeCompare(dirname(b.path)) || basename(a.path).localeCompare(basename(b.path)));
const byDir = new Map();
for (const f of files) {
  const d = relative(root, dirname(f.path)) || '.';
  if (!byDir.has(d)) byDir.set(d, []);
  byDir.get(d).push(f);
}

const parts = [];
const noted = new Set();
for (const [d, fs] of byDir) {
  parts.push(`### \`${d}/\`\n`);
  const appName = fs[0].app;
  if (appName && !noted.has(appName)) {
    noted.add(appName);
    parts.push(`*Source for \`${appName}\` (read-only copies): [browse all files](./${downloads}/${appName}/index.html) · [download .zip](./${downloads}/${appName}.zip)*\n`);
  }
  parts.push('| File | Description |', '| --- | --- |');
  for (const f of fs) {
    const name = basename(f.path);
    parts.push(`| [\`${name}\`](${f.href}) | ${describe(f.path) || '*(no header comment)*'} |`);
  }
  parts.push('');
}
const block = `${BEGIN}\n\n${parts.join('\n')}\n${END}`;

const skippedTotal = [...skipped.values()].reduce((a, b) => a + b, 0);
const missing = [...apps.keys()].filter((n) => !existsSync(join(root, downloads, n, 'index.html')));
const linkedNote = apps.size
  ? `linked to source downloads instead of the unpublished files: ${[...apps].map(([n, a]) => `${n} (${a.count})`).join(', ')}` +
    (missing.length ? `\nWARNING: no ${downloads}/<App>/index.html yet for ${missing.join(', ')}; run the Vite build first or the links will 404` : '')
  : '';
const skippedNote = skippedTotal
  ? `left out (not published by Jekyll, per ${join(jekyllSource, '_config.yml')}): ` +
    [...skipped].map(([p, n]) => (n > 1 || p.endsWith('/') ? `${p} (${n})` : p)).join(', ')
  : '';

if (flags.has('--stdout')) { if (linkedNote) console.error(linkedNote); if (skippedNote) console.error(skippedNote); console.log(block); process.exit(0); }

const readmePath = join(root, 'README.md');
const current = existsSync(readmePath) ? readFileSync(readmePath, 'utf8') : null;
const re = new RegExp(`${BEGIN.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${END}`);

let next;
if (current === null) next = `# Code\n\nJavaScript modules for this course.\n\n## Module index\n\n${block}\n`;
else if (re.test(current)) next = current.replace(re, () => block);
else next = `${current.trimEnd()}\n\n## Module index\n\n${block}\n`;

if (flags.has('--check')) {
  if (next !== current) { console.error('README.md is out of date; run gen-readme.mjs'); process.exit(1); }
  console.log(`README.md is up to date (${files.length} .mjs files)`);
} else {
  writeFileSync(readmePath, next);
  console.log(`wrote ${readmePath}: ${files.length} .mjs files in ${byDir.size} directories`);
}
if (linkedNote) console.log(linkedNote);
if (skippedNote) console.log(skippedNote);
